package org.vgk.hr.db.entity;

/**
 * Поддерживаемые значения, которые можно подставить в область PDF-шаблона.
 */
public enum TemplateFieldType {
    /**
     * Текущая календарная дата, отформатированная по dateFormat.
     */
    CURRENT_DATE,
    /**
     * Дата рождения, переданная в запросе генерации и отформатированная по dateFormat.
     */
    BIRTH_DATE,
    /**
     * Фамилия, имя и отчество, переданные в запросе генерации.
     */
    FULL_NAME
}
